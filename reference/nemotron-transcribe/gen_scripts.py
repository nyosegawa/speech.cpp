"""Writes src/families/nemotron-transcribe/scripts.inc: the code point ranges whose Unicode names start with the prefixes
by which NeMo Speech's _timestamp_units() (ctc_timestamp_utils.py) tells a transcript's script, in Python 3.12's
unicodedata, Unicode 15.0.0, which the reference runs: Korean by HANGUL; Japanese by HIRAGANA or KATAKANA; Chinese by
CJK UNIFIED IDEOGRAPH or CJK COMPATIBILITY IDEOGRAPH; and Thai by THAI.

usage: uv run --no-project --python 3.12 python gen_scripts.py ../../src/families/nemotron-transcribe/scripts.inc
"""

import sys
import unicodedata

assert unicodedata.unidata_version == "15.0.0", unicodedata.unidata_version
SCRIPTS = (
    ("kKorean", ("HANGUL",)),
    ("kJapanese", ("HIRAGANA", "KATAKANA")),
    ("kChinese", ("CJK UNIFIED IDEOGRAPH", "CJK COMPATIBILITY IDEOGRAPH")),
    ("kThai", ("THAI",)),
)


def ranges(prefixes):
    out, start = [], None
    for cp in range(0x110000):
        if unicodedata.name(chr(cp), "").startswith(prefixes):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


with open(sys.argv[1], "w") as f:
    f.write("// Generated by reference/nemotron-transcribe/gen_scripts.py from Unicode 15.0.0.\n")
    for name, prefixes in SCRIPTS:
        body = ",\n".join("    {0x%X, 0x%X}" % r for r in ranges(prefixes))
        f.write(f"static const CodepointRange {name}[] = {{\n{body}\n}};\n")
